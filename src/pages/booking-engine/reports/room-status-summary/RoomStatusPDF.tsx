import React from "react";
import { Document, Page, StyleSheet, Text, View } from "@react-pdf/renderer";
import { RoomSummaryItem, RoomStats } from "types/metricsTypes";
import { ReservationStatusEnum } from "constants/reservation";

export interface RoomSummaryPdfDocumentProps {
  propertyName: string;
  dateGenerated: string;
  timeGenerated: string;
  generatedBy: string;
  sets: RoomSummaryItem[][];
  maxRows: number;
  roomStats: RoomStats;
  hasDepartingRooms: boolean;
}

function isDeparting(room: RoomSummaryItem) {
  return room.reservation_status === ReservationStatusEnum.DEPARTING;
}

const styles = StyleSheet.create({
  page: {
    padding: 20,
    fontFamily: "Courier",
    fontSize: 7,
  },
  header: {
    flexDirection: "row",
    justifyContent: "space-between",
    alignItems: "flex-start",
    marginBottom: 12,
  },
  logo: {
    width: 48,
    height: 48,
  },
  divider: {
    width: "100%",
    height: 0.5,
    backgroundColor: "black",
  },
  clearDivider: {
    width: "100%",
    height: 0.5,
  },
  headerLeft: {
    flexDirection: "column",
  },
  headerRight: {
    alignItems: "flex-end",
  },
  title: {
    fontSize: 12,
    fontFamily: "Courier-Bold",
  },
  metaText: {
    fontSize: 9,
    marginTop: 2,
    fontFamily: "Courier-Bold",
  },
  tableHeaderRow: {
    flexDirection: "row",
    borderTopWidth: 0.5,
    borderBottomWidth: 0.5,
    borderColor: "#000",
    paddingVertical: 2,
  },
  tableRow: {
    flexDirection: "row",
  },
  columnSet: {
    flex: 1,
    flexDirection: "row",
  },
  columnSpacer: {
    width: 30,
  },
  thRoomNum: {
    width: "20%",
    paddingRight: 16,
    textAlign: "center",
    fontFamily: "Courier-Bold",
  },
  thRoomType: {
    width: "20%",
    fontFamily: "Courier-Bold",
  },
  thStatus: {
    width: "30%",
    fontFamily: "Courier-Bold",
  },
  tdRoomNum: {
    width: "20%",
    textAlign: "right",
    paddingRight: 16,
    paddingVertical: 1,
  },
  tdRoomType: {
    width: "20%",
    paddingVertical: 1,
  },
  tdStatus: {
    width: "30%",
    paddingVertical: 1,
  },
  footnote: {
    marginVertical: 8,
    fontSize: 7,
    fontFamily: "Courier-Bold",
  },
  summaryContainer: {
    flexDirection: "row",
    marginTop: 30,
  },
  summarySection: {
    flex: 1,
  },
  summaryTitleRow: {
    borderBottomWidth: 1,
    borderColor: "#000",
    paddingBottom: 2,
    marginBottom: 3,
  },
  summaryTitleText: {
    fontFamily: "Courier-Bold",
    fontSize: 8,
  },
  summaryRow: {
    flexDirection: "row",
    marginBottom: 1,
  },
  summaryCount: {
    width: 30,
    textAlign: "left",
    fontFamily: "Courier-Bold",
    fontSize: 8,
    marginRight: 6,
  },
  summaryLabelText: {
    fontSize: 8,
  },
  summaryCodeText: {
    fontFamily: "Courier-Bold",
    fontSize: 8,
  },
});

export function RoomSummaryPdfDocument({
  propertyName,
  dateGenerated,
  timeGenerated,
  generatedBy,
  sets,
  maxRows,
  roomStats,
  hasDepartingRooms,
}: RoomSummaryPdfDocumentProps) {
  return (
    <Document>
      <Page size="A4" orientation="landscape" style={styles.page}>
        <View style={styles.header}>
          <View style={styles.headerLeft}>
            <Text style={styles.title}>Room Status Summary Report</Text>
            {propertyName ? (
              <Text style={styles.metaText}>{propertyName}</Text>
            ) : null}
          </View>
          <View style={styles.headerRight}>
            <Text style={styles.metaText}>Date Generated: {dateGenerated}</Text>
            <Text style={styles.metaText}>Time Generated: {timeGenerated}</Text>
            <Text style={styles.metaText}>Generated By: {generatedBy}</Text>
          </View>
        </View>

        <View>
          <View style={styles.divider}></View>
          <View style={styles.clearDivider}></View>
          <View style={styles.tableHeaderRow}>
            {sets.map((_, setIdx) => (
              <React.Fragment key={setIdx}>
                <View style={styles.columnSet}>
                  <Text style={styles.thRoomNum}>Room #</Text>
                  <Text style={styles.thRoomType}>Room Type</Text>
                  <Text style={styles.thStatus}>HK Stat</Text>
                  <Text style={styles.thStatus}>FD Stat</Text>
                </View>
                {setIdx < sets.length - 1 && (
                  <View style={styles.columnSpacer} />
                )}
              </React.Fragment>
            ))}
          </View>

          {Array.from({ length: maxRows }).map((_, rowIdx) => (
            <View key={rowIdx} style={styles.tableRow}>
              {sets.map((set, setIdx) => {
                const room = set[rowIdx];
                return (
                  <React.Fragment key={setIdx}>
                    <View style={styles.columnSet}>
                      <Text style={styles.tdRoomNum}>
                        {room
                          ? `${room.room_number}${isDeparting(room) ? "*" : ""}`
                          : ""}
                      </Text>
                      <Text style={styles.tdRoomType}>
                        {room?.room_type ?? ""}
                      </Text>
                      <Text style={styles.tdStatus}>
                        {room?.housekeeping_status ?? ""}
                      </Text>
                      <Text style={styles.tdStatus}>
                        {room?.frontdesk_status ?? ""}
                      </Text>
                    </View>
                    {setIdx < sets.length - 1 && (
                      <View style={styles.columnSpacer} />
                    )}
                  </React.Fragment>
                );
              })}
            </View>
          ))}
        </View>
        <View style={{ ...styles.divider, marginTop: 16 }}></View>
        <Text style={styles.footnote}>*Room is expected to depart today</Text>
        {/* Double line border */}
        <View style={styles.divider}></View>
        <View style={styles.clearDivider}></View>
        <View style={styles.divider}></View>

        <View style={styles.summaryContainer}>
          <View style={{ flex: 1 }}></View>
          <View style={styles.summarySection}>
            <View style={styles.summaryTitleRow}>
              <Text style={styles.summaryTitleText}>Front Desk Stat Count</Text>
            </View>
            {roomStats.frontdesk_info.map((info) => (
              <View key={info.name} style={styles.summaryRow}>
                <Text style={styles.summaryCount}>
                  {roomStats.frontdesk_stats[info.name] ?? 0}
                </Text>
                <Text style={styles.summaryLabelText}>
                  <Text style={styles.summaryCodeText}>{info.name}</Text>
                  <Text>-{info.full_name}</Text>
                </Text>
              </View>
            ))}
          </View>

          <View style={{ ...styles.summarySection, marginLeft: 50 }}>
            <View style={styles.summaryTitleRow}>
              <Text style={styles.summaryTitleText}>
                House Keeping Stat Count
              </Text>
            </View>
            {roomStats.housekeeping_info.map((info) => (
              <View key={info.name} style={styles.summaryRow}>
                <Text style={styles.summaryCount}>
                  {roomStats.housekeeping_stats[info.name] ?? 0}
                </Text>
                <Text style={styles.summaryLabelText}>
                  <Text style={styles.summaryCodeText}>{info.name}</Text>
                  <Text>-{info.full_name}</Text>
                </Text>
              </View>
            ))}
          </View>
        </View>
      </Page>
    </Document>
  );
}
