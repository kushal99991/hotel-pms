import { jsPDF } from "jspdf";
import autoTable, { CellHookData } from "jspdf-autotable";
import { format } from "date-fns";
import exampleLogo from "assets/images/logo.png";

export const downloadPDF = async ({
  title,
  subtitle = "",
  columns,
  data,
  generatedBy,
  logoUrl,
  orientation = "portrait",
  parseCellCb,
}: {
  title: string;
  subtitle?: string;
  columns: string[];
  data: any[][];
  generatedBy?: string;
  logoUrl?: string;
  orientation?: "portrait" | "landscape";
  parseCellCb?: (cellData: CellHookData, document: jsPDF) => void;
}) => {
  const doc = new jsPDF({
    orientation,
    unit: "pt",
    format: "a4",
  });

  const x = 30;
  const y = 30;
  const size = 40;
  const radius = size / 2;
  const timestamp = `Generated on: ${format(new Date(), "PPpp")}`;

  // Utility to convert image to base64
  const convertImageUrlToBase64 = (imageUrl: string): Promise<string> => {
    return fetch(imageUrl)
      .then((response) => response.blob())
      .then((blob) => {
        return new Promise<string>((resolve, reject) => {
          const reader = new FileReader();
          reader.onloadend = () => {
            const base64String = reader.result as string;
            resolve(base64String.split(",")[1]);
          };
          reader.onerror = reject;
          reader.readAsDataURL(blob);
        });
      });
  };

  // Validate if logo URL is a valid image
  const isValidImage = async (url: string) => {
    try {
      const res = await fetch(url, { method: "HEAD" });
      return res.ok && res.headers.get("Content-Type")?.startsWith("image");
    } catch {
      return false;
    }
  };

  // Set image source: either valid logoUrl or fallback
  let imageBase64 = "";
  let imageExtension = "PNG";
  let sourceLogo = logoUrl;

  if (!(sourceLogo && (await isValidImage(sourceLogo)))) {
    sourceLogo = exampleLogo; // fallback
  }

  try {
    imageBase64 = await convertImageUrlToBase64(sourceLogo);
    imageExtension = sourceLogo.split(".").pop()?.toUpperCase() || "PNG";
  } catch (err) {
    console.warn("Logo conversion failed:", err);
  }

  // Draw circular logo
  doc.setFillColor(255, 255, 255);
  doc.ellipse(x + radius, y + radius, radius, radius, "F");
  doc.addImage(
    `data:image/${imageExtension.toLowerCase()};base64,${imageBase64}`,
    imageExtension,
    x,
    y,
    size,
    size,
    undefined,
    "FAST"
  );

  // Add text header
  const textX = orientation === "landscape" ? 600 : 320; // adjust for landscape
  let textY = 40;
  doc.setFont("helvetica", "bold").setFontSize(14).text(title, textX, textY);
  textY += 18;

  doc.setFont("helvetica", "normal").setFontSize(12);
  if (subtitle) doc.text(subtitle, textX, textY);
  textY += 16;
  doc.text(timestamp, textX, textY);
  textY += 16;
  if (generatedBy) doc.text(`Generated by: ${generatedBy}`, textX, textY);
  textY += 40;

  // Add table
  autoTable(doc, {
    head: [columns],
    body: data,
    startY: textY,
    styles: { fontSize: 8 },
    margin: { top: 60 },
    didParseCell: function (hookData) {
      const rowData = hookData.row.raw as { isGroupHeader?: boolean };
      if (rowData?.isGroupHeader) {
        hookData.cell.styles.fontStyle = "bold";
        hookData.cell.styles.fillColor = [240, 240, 240]; // light gray
        hookData.cell.styles.halign = "center";
      }
      parseCellCb?.(hookData, doc);
    },
  });

  doc.save(`${title.toLowerCase().replace(/\s+/g, "-")}.pdf`);
};
